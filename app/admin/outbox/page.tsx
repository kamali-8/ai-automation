'use client';

import { useState, useEffect } from 'react';
import {
  Mail,
  Send,
  Eye,
  Filter,
  Search,
  X,
  AlertCircle,
  CheckCircle2,
} from 'lucide-react';

interface OutboxEmail {
  id: string;
  recipientEmail: string;
  recipientName: string;
  subject: string;
  bodyHtml: string;
  bodyText: string;
  emailType: string;
  relatedTaskId: string | null;
  relatedInternshipId: string | null;
  simulatedStatus: string;
  sentAt: string;
  createdAt: string;
}

export default function EmailOutboxPage() {
  const [emails, setEmails] = useState<OutboxEmail[]>([]);
  const [loading, setLoading] = useState(true);
  const [selectedType, setSelectedType] = useState('');
  const [searchQuery, setSearchQuery] = useState('');
  const [previewEmail, setPreviewEmail] = useState<OutboxEmail | null>(null);

  useEffect(() => {
    loadEmails();
  }, [selectedType]);

  async function loadEmails() {
    setLoading(true);
    try {
      const url = selectedType
        ? `/api/admin/outbox?type=${encodeURIComponent(selectedType)}`
        : '/api/admin/outbox';
      const res = await fetch(url);
      const data = await res.json();
      setEmails(data.emails || []);
    } catch (err) {
      console.error('Failed to load outbox:', err);
    } finally {
      setLoading(false);
    }
  }

  const emailTypes = [
    { label: 'All Messages', value: '' },
    { label: 'Account Welcome', value: 'ACCOUNT_WELCOME' },
    { label: 'Task Assigned', value: 'TASK_ASSIGNED' },
    { label: 'Submission Confirmed', value: 'SUBMISSION_CONFIRMED' },
    { label: 'Review Feedback', value: 'REVIEW_FEEDBACK' },
    { label: 'Next Task', value: 'NEXT_TASK' },
    { label: 'Deadline Reminder', value: 'DEADLINE_REMINDER' },
    { label: 'Overdue Notice', value: 'TASK_OVERDUE' },
    { label: 'Internship Completed', value: 'INTERNSHIP_COMPLETED' },
  ];

  const filteredEmails = emails.filter((e) => {
    if (!searchQuery) return true;
    const q = searchQuery.toLowerCase();
    return (
      e.recipientName.toLowerCase().includes(q) ||
      e.recipientEmail.toLowerCase().includes(q) ||
      e.subject.toLowerCase().includes(q)
    );
  });

  return (
    <div>
      <div style={{ marginBottom: '24px' }}>
        <h1 style={{ fontSize: '26px', fontWeight: 700, color: '#29332B' }}>Simulated Email Outbox</h1>
        <p style={{ fontSize: '14px', color: '#69746B', marginTop: '4px' }}>
          Inspect all simulated email dispatches for welcome onboarding, assignments, evaluations, and reminders.
        </p>
      </div>

      {/* Prominent Simulated Disclaimer Banner */}
      <div className="alert-banner alert-warning" style={{ border: '2px dashed #B8D8B0', background: '#FAF8F1' }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>
          <AlertCircle size={20} color="#744210" />
          <div>
            <strong style={{ fontSize: '14px', color: '#29332B' }}>
              SIMULATED — NOT ACTUALLY SENT VIA EXTERNAL SMTP
            </strong>
            <div style={{ fontSize: '12px', color: '#69746B', marginTop: '2px' }}>
              In this local demo environment, no external email server or SMTP credentials are used.
              All messages generated by the internship automation lifecycle are logged directly to SQLite for preview and audit verification.
            </div>
          </div>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="card" style={{ padding: '16px 20px', marginBottom: '20px' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: '14px' }}>
          {/* Type Filter Pills */}
          <div style={{ display: 'flex', gap: '6px', flexWrap: 'wrap' }}>
            {emailTypes.map((t) => (
              <button
                key={t.value}
                onClick={() => setSelectedType(t.value)}
                className={`btn btn-sm ${selectedType === t.value ? 'btn-primary' : 'btn-secondary'}`}
                style={{ fontSize: '12px', padding: '5px 10px' }}
              >
                {t.label}
              </button>
            ))}
          </div>

          {/* Search Input */}
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px', minWidth: '240px' }}>
            <Search size={16} color="#69746B" />
            <input
              type="text"
              className="form-input"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search recipient or subject..."
              style={{ padding: '7px 12px', fontSize: '13px' }}
            />
          </div>
        </div>
      </div>

      {/* Outbox Table */}
      <div className="card">
        <div className="card-header">
          <div>
            <div className="card-title">Outbox Records ({filteredEmails.length})</div>
            <div className="card-subtitle">
              Chronological log of simulated outgoing intern communications
            </div>
          </div>
        </div>

        {loading ? (
          <div style={{ padding: '30px', textAlign: 'center', color: '#69746B' }}>Loading outbox...</div>
        ) : filteredEmails.length === 0 ? (
          <div style={{ padding: '30px', textAlign: 'center', color: '#69746B' }}>
            No simulated emails found matching your filter.
          </div>
        ) : (
          <div className="table-container">
            <table className="custom-table">
              <thead>
                <tr>
                  <th>Recipient</th>
                  <th>Subject</th>
                  <th>Email Category</th>
                  <th>Delivery Status</th>
                  <th>Dispatched At</th>
                  <th>Action</th>
                </tr>
              </thead>
              <tbody>
                {filteredEmails.map((email) => (
                  <tr key={email.id}>
                    <td>
                      <strong>{email.recipientName}</strong>
                      <div style={{ fontSize: '11px', color: '#69746B' }}>{email.recipientEmail}</div>
                    </td>
                    <td>
                      <div style={{ fontWeight: 600, color: '#29332B' }}>{email.subject}</div>
                    </td>
                    <td>
                      <span className="badge badge-neutral" style={{ fontSize: '11px' }}>
                        {email.emailType}
                      </span>
                    </td>
                    <td>
                      <span className="badge badge-success" style={{ fontSize: '11px' }}>
                        <CheckCircle2 size={11} />
                        <span>{email.simulatedStatus}</span>
                      </span>
                    </td>
                    <td style={{ fontSize: '12px', color: '#69746B' }}>
                      {new Date(email.createdAt).toLocaleString([], {
                        month: 'short',
                        day: 'numeric',
                        hour: '2-digit',
                        minute: '2-digit',
                      })}
                    </td>
                    <td>
                      <button
                        onClick={() => setPreviewEmail(email)}
                        className="btn btn-secondary btn-sm"
                      >
                        <Eye size={13} />
                        <span>Preview Email</span>
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* Email Preview Modal */}
      {previewEmail && (
        <div className="modal-overlay" onClick={() => setPreviewEmail(null)}>
          <div className="modal-content" onClick={(e) => e.stopPropagation()} style={{ maxWidth: '680px' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '16px', borderBottom: '1px solid #E3E7E1', paddingBottom: '12px' }}>
              <div>
                <span className="badge badge-neutral" style={{ marginBottom: '4px' }}>
                  {previewEmail.emailType} • {previewEmail.simulatedStatus}
                </span>
                <h3 style={{ fontSize: '18px', fontWeight: 700, color: '#29332B' }}>
                  {previewEmail.subject}
                </h3>
                <div style={{ fontSize: '12px', color: '#69746B' }}>
                  To: <strong>{previewEmail.recipientName}</strong> &lt;{previewEmail.recipientEmail}&gt;
                </div>
              </div>
              <button
                onClick={() => setPreviewEmail(null)}
                style={{ background: 'none', border: 'none', cursor: 'pointer', color: '#69746B' }}
              >
                <X size={20} />
              </button>
            </div>

            {/* Email Rendered Frame */}
            <div
              style={{
                border: '1px solid #E3E7E1',
                borderRadius: '8px',
                padding: '20px',
                backgroundColor: '#FAF8F1',
                maxHeight: '450px',
                overflowY: 'auto',
              }}
              dangerouslySetInnerHTML={{ __html: previewEmail.bodyHtml }}
            />

            <div style={{ display: 'flex', justifyContent: 'flex-end', marginTop: '16px' }}>
              <button
                onClick={() => setPreviewEmail(null)}
                className="btn btn-secondary btn-sm"
              >
                Close Preview
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}

